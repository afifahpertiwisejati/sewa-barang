let memoryCache: DatabaseSchema | null = null

function persistDb(data: DatabaseSchema) {
  memoryCache = data
  try {
    const dir = dirname(DB_PATH)
    if (!existsSync(dir)) {
      mkdirSync(dir, { recursive: true })
    }
    writeFileSync(DB_PATH, JSON.stringify(data, null, 2), 'utf-8')
  }
  catch {
    // Fallback to in-memory cache if filesystem is read-only
  }
}

export function getDatabase(): DatabaseSchema {
  if (memoryCache) {
    return memoryCache
  }

  try {
    if (existsSync(DB_PATH)) {
      const raw = readFileSync(DB_PATH, 'utf-8')
      const parsed = JSON.parse(raw) as DatabaseSchema
      if (
        Array.isArray(parsed.users)
        && parsed.users.length > 0
        && Array.isArray(parsed.items)
        && Array.isArray(parsed.bookings)
      ) {
        memoryCache = parsed
        syncAllItemStatuses(memoryCache)
        return memoryCache
      }
    }
  }
  catch {
    // Re-seed if file is unreadable or corrupt
  }

  const seed = createSeedData()
  syncAllItemStatuses(seed)
  persistDb(seed)
  return seed
}

export function saveDatabase(data: DatabaseSchema) {
  syncAllItemStatuses(data)
  persistDb(data)
}

export function datesOverlap(
  startA: string,
  endA: string,
  startB: string,
  endB: string,
): boolean {
  return startA <= endB && startB <= endA
}

export function calculateRentalDays(startDate: string, endDate: string): number {
  const start = new Date(`${startDate}T00:00:00`)
  const end = new Date(`${endDate}T00:00:00`)
  const diffMs = end.getTime() - start.getTime()
  const diffDays = Math.round(diffMs / (1000 * 60 * 60 * 24))
  return diffDays <= 0 ? 1 : diffDays
}

export function syncItemStatus(db: DatabaseSchema, itemId: string) {
  const item = db.items.find(i => i.id === itemId)
  if (!item) return

  const today = getOffsetDate(0)
  const hasCurrentActiveBooking = db.bookings.some(
    b =>
      b.itemId === itemId
      && b.status === 'aktif'
      && b.startDate <= today
      && b.endDate >= today,
  )

  item.status = hasCurrentActiveBooking ? 'Sedang Disewa' : 'Tersedia'
}

export function syncAllItemStatuses(db: DatabaseSchema) {
  for (const item of db.items) {
    syncItemStatus(db, item.id)
  }
}

export function updateBookingStatusInDb(
  id: string,
  status: BookingStatus,
): BookingRecord | null {
  const db = getDatabase()
  const booking = db.bookings.find(b => b.id === id)
  if (!booking) return null

  booking.status = status
  saveDatabase(db)
  return booking
}
