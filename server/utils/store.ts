function createLuxuryHeelsColors(base: string, primary: 'hitam' | 'burgundy' | 'ivory' | 'mahogany' = 'ivory'): ItemColorVariant[] {
  const all: Record<'hitam' | 'burgundy' | 'ivory' | 'mahogany', ItemColorVariant> = {
    hitam: { name: 'Hitam', hex: '#1C1C1E', imageUrl: `/images/${base}-hitam.jpg` },
    burgundy: { name: 'Burgundy', hex: '#6E1E2E', imageUrl: `/images/${base}-burgundy.jpg` },
    ivory: { name: 'Ivory', hex: '#EFE9DF', imageUrl: `/images/${base}-ivory.jpg` },
    mahogany: { name: 'Mahogany', hex: '#4F241D', imageUrl: `/images/${base}-mahogany.jpg` },
  }
  const order: Array<'hitam' | 'burgundy' | 'ivory' | 'mahogany'> = [
    primary,
    ...(['hitam', 'burgundy', 'ivory', 'mahogany'] as const).filter(k => k !== primary),
  ]
  return order.map(k => all[k])
}

